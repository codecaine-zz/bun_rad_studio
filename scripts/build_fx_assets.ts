// Writes the two files that carry a copy of the fx layer, so they cannot drift from src/shared/fx*.ts:
//   design_tokens.css          the portable token set; the drop-in classes sit between the fx:start / fx:end markers
//   src/ide/15_fx_layer.js     the Designer's part: theme table, CSS text, pointer helper and the canvas wiring
//
//   bun run fx:build    rewrite both
//   bun run fx:check    exit 1 when either is out of date
import { existsSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";
import { FX_THEMES, FX_THEME_ALIASES, fxCssVars, fxRootAttrs } from "../src/shared/fxThemes";
import { fxCss } from "../src/shared/fxCss";
import { FX_POINTER_FUNCTION } from "../src/shared/fxPointer";
import { contrastRatio, parseColor, toHex } from "../src/shared/themeSemantic";

const ROOT = join(import.meta.dir, "..");
export const TOKENS_FILE = join(ROOT, "design_tokens.css");
export const IDE_PART = join(ROOT, "src", "ide", "15_fx_layer.js");
export const START = "/* fx:start (generated by scripts/build_fx_assets.ts, edit src/shared/fxCss.ts instead) */";
export const END = "/* fx:end */";

const clean = (s: string) => s.toLowerCase().trim().replace(/[\s\-_]+/g, "_");
const mix = (a: string, b: string, t: number) => {
    const x = parseColor(a);
    const y = parseColor(b);
    return toHex([x[0] + (y[0] - x[0]) * t, x[1] + (y[1] - x[1]) * t, x[2] + (y[2] - x[2]) * t]);
};

export function designTokensBlock(): string {
    return `${START}\n${fxCss()}\n${END}`;
}

export function applyTokens(current: string): string {
    const a = current.indexOf(START);
    const b = current.indexOf(END);
    const block = designTokensBlock();
    if (a >= 0 && b > a) return current.slice(0, a) + block + current.slice(b + END.length);
    return current.replace(/\s*$/, "\n\n") + block + "\n";
}

export function designerThemeData() {
    const data: Record<string, unknown> = {};
    const lookup: Record<string, string> = {};
    for (const [key, t] of Object.entries(FX_THEMES)) {
        const card = t.card_background ?? t.background_color;
        const onAccent = contrastRatio(t.accent_color, "#ffffff") >= contrastRatio(t.accent_color, "#0b0b0f") ? "#ffffff" : "#0b0b0f";
        data[key] = {
            key,
            name: t.name,
            isDark: t.is_dark,
            palette: {
                formBg: t.background_color,
                formFg: t.font_color,
                ctrlBg: card,
                ctrlFg: t.font_color,
                btnBg: t.accent_color,
                btnFg: onAccent,
                panelBg: mix(card, t.is_dark ? "#ffffff" : "#000000", 0.06),
            },
            vars: fxCssVars(t),
            attrs: fxRootAttrs(t, "on"),
        };
        for (const n of [key, t.name, t.short_name ?? ""]) if (n) lookup[clean(n)] = key;
    }
    for (const [alias, key] of Object.entries(FX_THEME_ALIASES)) lookup[alias] = key;
    return { data, lookup };
}

export function idePart(): string {
    const { data, lookup } = designerThemeData();
    const fn = FX_POINTER_FUNCTION.split("\n").map((l) => "\t\t" + l).join("\n").trimStart();
    return `\t\t// GENERATED by scripts/build_fx_assets.ts from src/shared/fx*.ts. Do not edit by hand; run \`bun run fx:build\`.
\t\t// The futuristic theme layer for the Designer: theme table, effects CSS, pointer helper and the canvas wiring.
\t\tvar FX_CSS_TEXT = ${JSON.stringify(fxCss())};
\t\tvar FX_THEME_DATA = ${JSON.stringify(data)};
\t\tvar FX_THEME_LOOKUP = ${JSON.stringify(lookup)};
\t\tvar FX_POINTER_FN = ${fn};
\t\tvar fxState = { sig: null, pointer: null };

\t\tfunction fxThemeFor(name) {
\t\t\tconst key = FX_THEME_LOOKUP[String(name || "").toLowerCase().trim().replace(/[\\s\\-_]+/g, "_")];
\t\t\treturn key ? FX_THEME_DATA[key] : null;
\t\t}

\t\t// The palette getRawThemeColors returns for a futuristic theme, or null for every other theme.
\t\tfunction fxPaletteFor(name) {
\t\t\tconst t = fxThemeFor(name);
\t\t\treturn t ? Object.assign({}, t.palette) : null;
\t\t}

\t\tfunction fxStyleEl(id) {
\t\t\tlet el = document.getElementById(id);
\t\t\tif (!el) { el = document.createElement("style"); el.id = id; document.head.appendChild(el); }
\t\t\treturn el;
\t\t}

\t\t// Turns the effects layer on or off for the form canvas and the toolbar and tab chrome, following formSpec.theme and formSpec.fx_mode.
\t\t// The code editor and the properties panel never get it: no blur behind code, no scanlines over text you edit.
\t\tfunction applyFxToCanvas() {
\t\t\tconst canvas = document.getElementById("formCanvas");
\t\t\tif (!canvas) return;
\t\t\tconst t = fxThemeFor(formSpec.theme);
\t\t\tconst mode = formSpec.fx_mode === "off" ? "off" : (formSpec.fx_mode === "reduced" ? "reduced" : "on");
\t\t\tconst sig = (t ? t.key : "") + "|" + mode;
\t\t\tif (fxState.sig === sig) return;
\t\t\tfxState.sig = sig;
\t\t\tconst live = !!t && mode !== "off";
\t\t\tArray.prototype.slice.call(canvas.attributes).forEach(function (a) { if (a.name.indexOf("data-fx") === 0) canvas.removeAttribute(a.name); });
\t\t\tcanvas.classList.toggle("fx-root", live);
\t\t\tif (live) {
\t\t\t\tObject.keys(t.attrs).forEach(function (k) { canvas.setAttribute(k, t.attrs[k]); });
\t\t\t\tcanvas.setAttribute("data-fx", mode);
\t\t\t}
\t\t\tconst chrome = [[".app-header", null], [".tab-bar", "fx-nav"], [".canvas-toolbar", "fx-toolbar"], [".toolbar-actions", "fx-toolbar"]];
\t\t\tchrome.forEach(function (c) {
\t\t\t\tdocument.querySelectorAll(c[0]).forEach(function (el) {
\t\t\t\t\tif (live) el.setAttribute("data-fx", mode); else el.removeAttribute("data-fx");
\t\t\t\t\tif (c[1]) el.classList.toggle(c[1], live);
\t\t\t\t});
\t\t\t});
\t\t\tdocument.querySelectorAll(".app-header .btn").forEach(function (b) { b.classList.toggle("fx-button", live); });
\t\t\tif (t) {
\t\t\t\tfxStyleEl("fxDesignerVars").textContent = ":root { " + t.vars + " }";
\t\t\t\tconst css = fxStyleEl("fxDesignerCss");
\t\t\t\tif (!css.textContent) css.textContent = FX_CSS_TEXT;
\t\t\t} else {
\t\t\t\tconst vars = document.getElementById("fxDesignerVars");
\t\t\t\tif (vars) vars.textContent = "";
\t\t\t}
\t\t\tif (live && !fxState.pointer) fxState.pointer = FX_POINTER_FN(window);
\t\t\tif (!live && fxState.pointer) { fxState.pointer.dispose(); fxState.pointer = null; }
\t\t\tif (fxState.pointer) fxState.pointer.refresh();
\t\t}

\t\t// Keeps the theme and effects selects in step with the form (after a restore, an import, an undo or a new form).
\t\tfunction syncThemeControls() {
\t\t\tconst themeSel = document.getElementById("propFormTheme");
\t\t\tif (themeSel && formSpec.theme && themeSel.value !== formSpec.theme) {
\t\t\t\tfor (let i = 0; i < themeSel.options.length; i++) {
\t\t\t\t\tif (themeSel.options[i].value === formSpec.theme) { themeSel.value = formSpec.theme; break; }
\t\t\t\t}
\t\t\t}
\t\t\tconst fxSel = document.getElementById("propFormFx");
\t\t\tconst wanted = formSpec.fx_mode || "full";
\t\t\tif (fxSel && fxSel.value !== wanted) fxSel.value = wanted;
\t\t\tapplyFxToCanvas();
\t\t}

\t\tfunction updateFxMode() {
\t\t\tsaveHistoryState();
\t\t\tconst sel = document.getElementById("propFormFx");
\t\t\tformSpec.fx_mode = sel ? sel.value : "full";
\t\t\trenderCanvas();
\t\t\tsyncSpecToV();
\t\t\tdocument.getElementById("statusMsg").textContent = "Effects set to " + formSpec.fx_mode + ".";
\t\t}
`;
}

const lf = (s: string) => s.replace(/\r\n/g, "\n");

export function main(args: string[]): number {
    const check = args.includes("--check");
    const tokens = existsSync(TOKENS_FILE) ? readFileSync(TOKENS_FILE, "utf8") : "";
    const wantedTokens = applyTokens(lf(tokens));
    const wantedPart = idePart();
    const stale: string[] = [];
    if (lf(tokens) !== wantedTokens) stale.push("design_tokens.css");
    if (!existsSync(IDE_PART) || lf(readFileSync(IDE_PART, "utf8")) !== wantedPart) stale.push("src/ide/15_fx_layer.js");
    if (check) {
        if (stale.length) {
            console.error(`Out of date: ${stale.join(", ")}. Run: bun run fx:build`);
            return 1;
        }
        console.log("fx assets are up to date.");
        return 0;
    }
    writeFileSync(TOKENS_FILE, wantedTokens);
    writeFileSync(IDE_PART, wantedPart);
    console.log(`Wrote design_tokens.css and src/ide/15_fx_layer.js${stale.length ? ` (updated: ${stale.join(", ")})` : " (no change)"}`);
    return 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
