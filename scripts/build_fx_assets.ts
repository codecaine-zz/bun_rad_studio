export function designerThemeData() {
  const data: Record<string, unknown> = {};
  const lookup: Record<string, string> = {};
  for (const [key, t] of Object.entries(FX_THEMES)) {
    const card = t.card_background ?? t.background_color;
    const onAccent =
      contrastRatio(t.accent_color, "#ffffff") >=
      contrastRatio(t.accent_color, "#0b0b0f")
        ? "#ffffff"
        : "#0b0b0f";
    data[key] = {
      key,
      name: t.name,
      isDark: t.is_dark,
      palette: {
        formBg: t.background_color,
        formFg: t.font_color,
        ctrlBg: card,
        ctrlFg: t.font_color,
        btnBg: t.accent_color,
        btnFg: onAccent,
        panelBg: mix(card, t.is_dark ? "#ffffff" : "#000000", 0.06),
      },
      cb: t.card_border,
      fx: t.fx,
    };
    for (const n of [key, t.name, t.short_name ?? ""])
      if (n) lookup[clean(n)] = key;
  }
  for (const [alias, key] of Object.entries(FX_THEME_ALIASES))
    lookup[alias] = key;
  return { data, lookup };
}

