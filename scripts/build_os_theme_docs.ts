// Writes the "Linux distributions, Windows versions and macOS versions" and "status colors" sections of
// docs/THEMES.md from the real theme data, between two marker comments, so the page cannot drift from the code.
//   bun run scripts/build_os_theme_docs.ts           rewrite the block
//   bun run scripts/build_os_theme_docs.ts --check   exit 1 if the block is out of date
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";
import { OS_THEMES, RARE_OS_THEME_KEYS } from "../src/shared/osThemes";
import { FX_THEMES } from "../src/shared/fxThemes";
import { getSemanticColors, getThemeNames } from "../src/simplegui";

export const START = "<!-- os-themes:start -->";
export const END = "<!-- os-themes:end -->";
export const FX_START = "<!-- fx-themes:start -->";
export const FX_END = "<!-- fx-themes:end -->";
/** The three themes whose hover, focus, row and card states are captured in screenshots/themes/fx/. */
export const FX_STATE_SHOTS = ["cyberpunk_hologram", "quantum_obsidian", "liquid_metal_light"];

interface Group {
    id: string;
    title: string;
    intro: string;
    keys: string[];
}

export function groups(): Group[] {
    const keys = Object.keys(OS_THEMES);
    const windows = ["win31", "win98", "win2000", "winxp_luna", "vista_aero", "win7_aero", "win8_metro", "win10_dark", "win10_light", "windows_terminal", "windows_high_contrast"];
    const mac = ["mac_os_9", "snow_leopard", "yosemite", "big_sur", "monterey_light", "sequoia_dark", "tahoe_glass"];
    return [
        { id: "os-linux", title: "🐧 Linux Distributions & Desktop Environments", intro: "One theme per major distribution, desktop environment and popular GTK theme, built from each project's own colors.", keys: keys.filter((k) => !windows.includes(k) && !mac.includes(k) && !RARE_OS_THEME_KEYS.includes(k)) },
        { id: "os-windows", title: "🪟 Windows Versions", intro: "Windows 3.1 through Windows 11, plus the Windows Terminal and High Contrast schemes.", keys: windows },
        { id: "os-macos", title: "🍎 macOS Versions", intro: "Mac OS 9 Platinum through macOS Tahoe.", keys: mac },
        { id: "os-rare", title: "💾 Rare & Beloved Systems", intro: "Desktops and devices many people loved but may never have seen: BeOS and Haiku, OS/2 Warp, Solaris CDE, SGI IRIX, Atari GEM, RISC OS, QNX Photon, Symbian, Palm OS and webOS, Windows Phone, Zune, Android Holo, Longhorn, Media Center, Plan 9 Acme, SerenityOS, KDE 3 Keramik, Bluecurve, Ubuntu Human and Window Maker.", keys: RARE_OS_THEME_KEYS },
    ];
}

const mode = (dark: boolean) => (dark ? "🌙 Dark" : "☀️ Light");

export function buildBlock(): string {
    const lines: string[] = [START, "", "<!-- Generated by scripts/build_os_theme_docs.ts. Edit src/shared/osThemes.ts, not this block. -->", ""];
    for (const g of groups()) {
        lines.push(`<a id="${g.id}"></a>`, `## ${g.title} (${g.keys.length} Themes)`, "", g.intro, "");
        lines.push("| Theme Key | Display Name | Mode | Primary Accent | Secondary | Canvas | Card | Text | Screenshot |", "|---|---|---|---|---|---|---|---|---|");
        for (const k of g.keys) {
            const t = OS_THEMES[k]!;
            lines.push(`| \`${k}\` | **${t.name}** | ${mode(t.is_dark)} | \`${t.accent_color}\` | \`${t.secondary_accent}\` | \`${t.background_color}\` | \`${t.card_background}\` | \`${t.font_color}\` | [🖼️](../screenshots/themes/${k}.png) |`);
        }
        lines.push("", "Try one live: `bun run demo:themes " + (g.keys[0] ?? "") + "`", "");
        for (const k of g.keys) {
            const t = OS_THEMES[k]!;
            lines.push(`<a id="theme-${k}"></a>`, `### ${t.name} (\`${k}\`)`, "", `> ${t.description}`, "", `![${t.name} Showcase](../screenshots/themes/${k}.png)`, "");
        }
        lines.push("---", "");
    }
    lines.push(
        '<a id="status-colors"></a>',
        "## 🚦 Status colors: danger, warning, success, info",
        "",
        "Every theme has four status colors. They are worked out from the theme so they always read well on its canvas and cards (text at least 4.5:1 where the canvas allows it, fills at least 3:1 against the card, and the label on a fill at least 4.5:1). Well-known palettes (Dracula, Nord, Gruvbox, Solarized, Catppuccin, Monokai Pro, Tokyo Night, One Dark, GitHub, Everforest, Kanagawa and the classic Windows palettes) use their own published colors.",
        "",
        "```ts",
        'const sem = simplegui.getSemanticColors("dracula");   // sem.danger.solid, .on, .text, .soft, .border (same for warning, success, info)',
        'win.addButton("del", "Delete", { variant: "danger" });                     // solid',
        'win.addButton("save", "Save", { variant: "success", appearance: "soft" }); // soft tint; "outline" also works',
        'win.addBadge("Late", "warning");                                           // badges, alerts, toasts and status dots use the same colors',
        "```",
        "",
        "In CSS they are variables that follow the theme, including after a live theme switch: `--danger`, `--danger-on`, `--danger-text`, `--danger-soft`, `--danger-border`, and the same for `--warning`, `--success`, `--info`.",
        "",
        "| Theme | Danger | Warning | Success | Info |",
        "|---|---|---|---|---|",
    );
    for (const k of ["ubuntu_dark", "ubuntu_light", "dracula", "nord", "solarized_light", "github_dark", "win95", "windows_high_contrast", "debian_dark", "tahoe_glass"]) {
        const s = getSemanticColors(k);
        lines.push(`| \`${k}\` | \`${s.danger.solid}\` | \`${s.warning.solid}\` | \`${s.success.solid}\` | \`${s.info.solid}\` |`);
    }
    lines.push("", END);
    return lines.join("\n");
}

export function apply(doc: string, block: string): string {
    const a = doc.indexOf(START);
    const b = doc.indexOf(END);
    if (a >= 0 && b > a) return doc.slice(0, a) + block + doc.slice(b + END.length);
    const anchor = '<a id="quick-reference-index"></a>';
    const at = doc.indexOf(anchor);
    if (at < 0) throw new Error("docs/THEMES.md has no quick-reference-index anchor");
    return doc.slice(0, at) + block + "\n\n" + doc.slice(at);
}

export function buildFxBlock(): string {
    const entries = Object.entries(FX_THEMES);
    const lines: string[] = [FX_START, "", "<!-- Generated by scripts/build_os_theme_docs.ts. Edit src/shared/fxThemes.ts, not this block. -->", ""];
    lines.push(
        '<a id="fx-themes"></a>',
        `## 🌌 Futuristic Themes (${entries.length} Themes)`,
        "",
        `Glass surfaces, edge glow, a slow living backdrop and a motion layer (button bloom, floating labels, sliding tab pill, tilting cards). Every theme here carries an \`fx\` descriptor; the other ${getThemeNames().length - entries.length} themes render exactly as before. Body text on glass is checked at 4.5:1 over both a black and a white backdrop, and the effects respect \`prefers-reduced-motion\`, \`prefers-contrast\` and forced colors. Guide: [fx-themes developer guide](developer/fx-themes.md).`,
        "",
        "| Theme Key | Display Name | Mode | Primary Accent | Secondary | Canvas | Card | Text | Glow | Glass | Motion | Border | Screenshot |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    );
    for (const [k, t] of entries) {
        const fx = t.fx!;
        lines.push(`| \`${k}\` | **${t.name}** | ${mode(t.is_dark)} | \`${t.accent_color}\` | \`${t.secondary_accent}\` | \`${t.background_color}\` | \`${t.card_background}\` | \`${t.font_color}\` | ${fx.glow} | ${fx.glass} | ${fx.motion} | ${fx.border} | [view](#theme-${k}) |`);
    }
    lines.push("", "Try one live: `bun run demo:themes " + (entries[0]?.[0] ?? "") + "`", "");
    for (const [k, t] of entries) {
        const fx = t.fx!;
        const bits = [`glow ${fx.glow} (${fx.glowColor}${fx.glowColor2 ? ` + ${fx.glowColor2}` : ""})`, `blur ${fx.blur}px`, `glass ${fx.glass}`, `radius ${fx.radius}`, `border ${fx.border}`, `motion ${fx.motion}`];
        if (fx.scanlines === "subtle") bits.push("scanlines");
        if (fx.grain === "subtle") bits.push("grain");
        if (fx.sheen) bits.push("sheen");
        if (fx.noise) bits.push("noise");
        if (fx.chromatic) bits.push("chromatic headings");
        if (fx.ambient) bits.push("ambient backdrop");
        lines.push(`<a id="theme-${k}"></a>`, `### ${t.name} (\`${k}\`)`, "", `> ${t.description}`, "", `- **fx**: ${bits.join(", ")}`, "", `![${t.name} Showcase](../screenshots/themes/${k}.png)`, "");
    }
    lines.push(
        '<a id="fx-states"></a>',
        "### Interaction states",
        "",
        "Captured from a real browser with the pointer parked on each element (the browser tab is hidden while capturing, so transitions are finished before each capture; the images show the end state of each interaction).",
        "",
    );
    for (const k of FX_STATE_SHOTS) lines.push(`**${FX_THEMES[k]!.name}**`, "", `![${FX_THEMES[k]!.name} interaction states](../screenshots/themes/fx/${k}_states.png)`, "");
    lines.push(
        '<a id="fx-effects-switch"></a>',
        "### Turning effects down or off",
        "",
        "```ts",
        'const win = simplegui.createWindow("App", 900, 600, { theme: "neon_hud", effects: "reduced" }); // "full" (default), "reduced" or "off"',
        'win.setEffects("off");                                                                          // live switch, no reload',
        "```",
        "",
        "In the Visual Designer the **Effects** control next to **Form Theme** does the same and is saved with the form. Full follows the system's reduced-motion setting automatically.",
        "",
        "---",
        "",
        FX_END,
    );
    return lines.join("\n");
}

export function applyFx(doc: string, block: string): string {
    const a = doc.indexOf(FX_START);
    const b = doc.indexOf(FX_END);
    if (a >= 0 && b > a) return doc.slice(0, a) + block + doc.slice(b + FX_END.length);
    const at = doc.indexOf(END);
    if (at < 0) throw new Error("docs/THEMES.md has no os-themes block to place the futuristic block after");
    const after = at + END.length;
    return doc.slice(0, after) + "\n\n" + block + doc.slice(after);
}

if (import.meta.main) {
    const file = join(import.meta.dir, "..", "docs", "THEMES.md");
    const current = readFileSync(file, "utf8");
    const next = applyFx(apply(current, buildBlock()), buildFxBlock());
    if (process.argv.includes("--check")) {
        if (next !== current) {
            console.error("docs/THEMES.md is out of date. Run: bun run scripts/build_os_theme_docs.ts");
            process.exit(1);
        }
        console.log("docs/THEMES.md is up to date.");
    } else {
        writeFileSync(file, next);
        console.log("wrote docs/THEMES.md");
    }
}
