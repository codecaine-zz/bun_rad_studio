import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "fs";
import { basename, dirname, join, relative } from "path";
import { DOCS, ROOT, loadNav } from "./check_docs";
import { isHeadless } from "../app_status";

/**
 * Generates the parts of the handbook that must never drift from the code:
 *   docs/toc.md                                          global table of contents (from docs/nav.json)
 *   docs/reference/application-index.md                  every tool the launcher detects
 *   docs/documentation-maintenance/coverage-matrix.md    coverage matrix (apps + hand-kept feature rows)
 * `bun scripts/docs/build_docs.ts` writes them; `--check` fails when they are out of date.
 */

const NOTICE = "<!-- GENERATED by scripts/docs/build_docs.ts - do not edit by hand; run `bun run docs:build` -->";

type Status = "Implemented and verified" | "Implemented but not verified" | "Partially implemented" | "Planned" | "Unsupported" | "Unknown";

interface FeatureRow {
  name: string;
  audience: string;
  evidence: string[];
  page: string;
  implementation: Status;
  verification: string;
  missing: string;
}

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const posix = (p: string) => p.split("\\").join("/");

function readTests(): { path: string; text: string }[] {
  const out: { path: string; text: string }[] = [];
  const walk = (dir: string) => {
    // Sorted: the order readdirSync returns differs between file systems, and the order ends up in generated pages.
    for (const n of readdirSync(dir).sort()) {
      if (n === "node_modules" || n === "dist" || n.startsWith(".")) continue;
      const p = join(dir, n);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.test\.(ts|mjs)$/.test(n) || /\.node\.mjs$/.test(n)) out.push({ path: posix(relative(ROOT, p)), text: readFileSync(p, "utf8") });
    }
  };
  walk(join(ROOT, "tests"));
  walk(join(ROOT, "src"));
  return out;
}

/** First descriptive comment of a source file (real evidence of purpose), or "". */
function headerComment(file: string): string {
  const text = readFileSync(file, "utf8").slice(0, 4000);
  const block = /\/\*\*?([\s\S]*?)\*\//.exec(text);
  const raw = block && text.slice(0, block.index).trim() === "" ? block[1]! : (text.match(/^(?:\/\/[^\n]*\n)+/)?.[0] ?? "");
  const lines = raw
    .split("\n")
    .map((l) => l.replace(/^\s*(\*|\/\/)\s?/, "").trim())
    .filter((l) => l && !/^[=\-─]+$/.test(l) && !/^@/.test(l));
  return (lines[0] ?? "").replace(/\s+/g, " ").slice(0, 160);
}

export async function renderAll(): Promise<Record<string, string>> {
  const { scanAllApplications } = await import("../../applications/launcher_studio");
  const { apps } = scanAllApplications();
  const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")) as { scripts: Record<string, string> };
  const features = JSON.parse(readFileSync(join(DOCS, "documentation-maintenance", "features.json"), "utf8")) as { features: FeatureRow[]; verifiedLaunches: Record<string, string> };
  const tests = readTests();

  const aliases = new Map<string, string[]>();
  for (const [name, cmd] of Object.entries(pkg.scripts)) {
    const m = /\bbun run (\S+\.ts)\b/.exec(cmd);
    if (!m) continue;
    const key = m[1]!.replace(/^\.\//, "");
    aliases.set(key, [...(aliases.get(key) ?? []), name]);
  }

  // legacy generated guides -> app path (via the `bun run <script>` commands they mention)
  const guideDir = join(DOCS, "userguides");
  const guideFor = new Map<string, string>();
  for (const f of readdirSync(guideDir).filter((n) => /^\d+_.*\.md$/.test(n)).sort()) {
    const text = readFileSync(join(guideDir, f), "utf8");
    for (const m of text.matchAll(/bun run ([a-z0-9:_-]+)/g)) {
      const cmd = pkg.scripts[m[1]!];
      const target = cmd ? /\bbun run (\S+\.ts)\b/.exec(cmd)?.[1]?.replace(/^\.\//, "") : undefined;
      if (target && !guideFor.has(target)) guideFor.set(target, `userguides/${f}`);
    }
  }

  const rows = apps
    .map((a) => ({ ...a, rel: posix(relative(ROOT, a.path)) }))
    .sort((x, y) => x.source.localeCompare(y.source) || x.displayName.localeCompare(y.displayName));
  const sourceLabel: Record<string, string> = { rad_studio: "Studio", cli_tool: "CLI tool", rad_demo: "Demo" };
  const counts: Record<string, number> = { rad_studio: 0, cli_tool: 0, rad_demo: 0 };
  for (const r of rows) counts[r.source] = (counts[r.source] ?? 0) + 1;

  // ---------------- application index ----------------
  let idx = `# Application index\n\n${NOTICE}\n\nEvery tool that the launcher detects in this repository (\`bun run cli:launcher --list\`). **${rows.length} tools**: ${counts.rad_studio} studios (windowed apps), ${counts.cli_tool} command-line tools and ${counts.rad_demo} demos.\n\n`;
  idx += "The launcher does **not** list itself (`applications/launcher_studio.ts`, [guide](../getting-started/install-and-first-launch.md#step-5-open-the-launcher)) and hides helper files whose names contain `_server.`, `_crud.`, `_engine.` or `_ops.`; so the visual designer (`index.ts`) and the launcher are not in this table either.\n\n";
  idx += "The *Automated start check* column (studios only) is what `tests/applications_smoke.test.ts` verifies on every test run: either the studio starts headless with `--server` and answers `GET /` with an HTML page, or its module loads in a fresh process without error. **It never checks the native window or any feature inside the studio.** The *Launch command* column is the command the launcher itself uses; *Short name* is a `package.json` script, when one exists. A launch command being listed does **not** mean the tool was run for this handbook: see the [coverage matrix](../documentation-maintenance/coverage-matrix.md) for what was verified. Descriptions come from the launcher's built-in list or the file's own header comment; \"(none in source)\" means the code has no description.\n\n";
  idx += "## Contents\n\n- [Studios](#studios)\n- [Command-line tools](#command-line-tools)\n- [Demos](#demos)\n\n";
  const section = (title: string, src: string) => {
    const withCheck = src === "rad_studio";
    let s = `## ${title}\n\n| Name | Category | Short name | Launch command | Description |${withCheck ? " Automated start check |" : ""}\n|---|---|---|---|---|${withCheck ? "---|" : ""}\n`;
    for (const r of rows.filter((x) => x.source === src)) {
      const hdr = headerComment(r.path);
      const generic = /^(Native Bun RAD Studio application|Command-line terminal utility for|Bun RAD Studio visual showcase template)/.test(r.description);
      const desc = generic ? hdr || "(none in source)" : r.description;
      const short = (aliases.get(r.rel) ?? []).map((n) => `\`bun run ${n}\``).join(", ") || "-";
      const check = withCheck ? ` ${isHeadless(readFileSync(r.path, "utf8")) ? "Starts with `--server` and serves its page" : "Module loads; window not opened"} |` : "";
      s += `| ${cell(r.displayName)} | ${cell(r.category)} | ${short} | \`${cell(r.command)}\` | ${cell(desc)} |${check}\n`;
    }
    return s + "\n";
  };
  idx += section("Studios", "rad_studio") + section("Command-line tools", "cli_tool") + section("Demos", "rad_demo");

  // ---------------- coverage matrix ----------------
  const pageLink = (p: string) => (existsSync(join(DOCS, p)) ? `[${p}](../${p})` : `(not written yet) \`${p}\``);
  let cov = `# Documentation coverage matrix\n\n${NOTICE}\n\nGenerated from the launcher's detected tools plus the hand-kept rows in [features.json](features.json). Status vocabulary:\n\n`;
  cov += "| State | Meaning |\n|---|---|\n| Implemented and verified | The behaviour was run or covered by automated tests, and the *Verification* column says how and when. |\n| Implemented but not verified | The code exists but nobody has run it for this documentation. |\n| Partially implemented | Some of it works, or it is a placeholder/sample. |\n| Planned | Does not exist yet; must not be described as available. |\n| Unsupported | Known not to work or intentionally not supported. |\n| Unknown | Not yet investigated. |\n\n";
  cov += "## Contents\n\n- [Features and workflows](#features-and-workflows)\n- [Applications](#applications)\n- [Summary](#summary)\n\n";
  cov += "## Features and workflows\n\n| Feature | Audience | Source evidence | Documentation page | Implementation status | Verification status | Missing information |\n|---|---|---|---|---|---|---|\n";
  const tally = new Map<string, number>();
  const featureTally = new Map<string, number>();
  for (const f of features.features) {
    featureTally.set(f.implementation, (featureTally.get(f.implementation) ?? 0) + 1);
    cov += `| ${cell(f.name)} | ${cell(f.audience)} | ${cell(f.evidence.map((e) => `\`${e}\``).join(", ") || "-")} | ${pageLink(f.page)} | ${f.implementation} | ${cell(f.verification)} | ${cell(f.missing)} |\n`;
  }
  cov += "\n## Applications\n\nOne row per detected tool. *Verification status* lists automated test files that mention the tool's source file; a launch is only called verified where [features.json](features.json) records one. Guides in `userguides/` are older, script-generated pages whose accuracy has **not** been checked (see [discrepancies](discrepancies.md)).\n\n";
  cov += "| Application | Audience | Source evidence | Documentation page | Implementation status | Verification status | Missing information |\n|---|---|---|---|---|---|---|\n";
  for (const r of rows) {
    const base = basename(r.rel).replace(/\.(ts|js)$/, "");
    const t = tests.filter((x) => x.text.includes(`/${base}`) || x.text.includes(`"${base}.ts"`)).map((x) => x.path);
    const audience = r.source === "rad_studio" ? (/Game|Entertainment/.test(r.category) ? "Everyday users" : "Everyday users, developers") : "Developers";
    const guide = guideFor.get(r.rel);
    const verified = features.verifiedLaunches[r.name] ?? features.verifiedLaunches[`${r.source === "cli_tool" ? "cli_" : "studio_"}${r.name}`];
    const impl: Status = verified ? "Implemented and verified" : "Implemented but not verified";
    const ver = verified ?? (t.length ? `Automated tests mention it: ${t.slice(0, 3).map((x) => `\`${x}\``).join(", ")}${t.length > 3 ? ` (+${t.length - 3})` : ""}. Launch not verified.` : "No automated test mentions it; launch not verified.");
    tally.set(impl, (tally.get(impl) ?? 0) + 1);
    const missing = guide ? "Legacy guide not checked against the code; no verified interface tour." : "No guide.";
    cov += `| ${cell(r.displayName)} (${sourceLabel[r.source]}) | ${audience} | \`${r.rel}\` | ${guide ? `[${guide}](../${guide})` : "-"} | ${impl} | ${cell(ver)} | ${missing} |\n`;
  }
  cov += "\n## Summary\n\n| Implementation status | Feature rows | Application rows |\n|---|---|---|\n";
  for (const s of ["Implemented and verified", "Implemented but not verified", "Partially implemented", "Planned", "Unsupported", "Unknown"]) cov += `| ${s} | ${featureTally.get(s) ?? 0} | ${tally.get(s) ?? 0} |\n`;
  cov += "\nApplication rows only say that the code exists and was detected by the launcher; they say nothing about whether the tool works.\n";

  // ---------------- table of contents ----------------
  const nav = loadNav();
  let toc = `# Table of contents\n\n${NOTICE}\n\nGenerated from [nav.json](nav.json): a page that is not listed there is reported by \`bun run docs:check\`.\n\n`;
  for (const s of nav.sections) {
    toc += `## ${s.title}\n\n`;
    for (const p of s.pages) toc += `- [${p.title}](${p.path})\n`;
    toc += "\n";
  }
  // ---------------- script index ----------------
  const groups: [string, (n: string) => boolean][] = [
    ["Studios (`app:*`)", (n) => n.startsWith("app:")],
    ["Command-line tools (`cli:*`)", (n) => n.startsWith("cli:")],
    ["Demos (`demo:*`)", (n) => n.startsWith("demo:")],
    ["Everything else", () => true],
  ];
  let scr = `# Script index\n\n${NOTICE}\n\nEvery script in \`package.json\`, run as \`bun run <name>\` from the repository root (\`bun start\` and \`bun test\` also work without \`run\`). **${Object.keys(pkg.scripts).length} scripts.** Being listed here does not mean the script was run for this handbook; see the [coverage matrix](../documentation-maintenance/coverage-matrix.md) and [Install and first launch](../getting-started/install-and-first-launch.md) for what was verified.\n\n`;
  scr += "## Contents\n\n" + groups.map(([t]) => `- [${t.replace(/`/g, "")}](#${t.toLowerCase().replace(/`/g, "").replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-").replace(/-+$/, "")})`).join("\n") + "\n\n";
  const taken = new Set<string>();
  for (const [title, test] of groups) {
    const names = Object.keys(pkg.scripts).filter((n) => !taken.has(n) && test(n));
    scr += `## ${title}\n\n| Script | Runs |\n|---|---|\n`;
    for (const n of names) {
      taken.add(n);
      scr += `| \`bun run ${n}\` | \`${cell(pkg.scripts[n]!)}\` |\n`;
    }
    scr += "\n";
  }

  return {
    "docs/reference/script-index.md": scr,
    "docs/toc.md": toc,
    "docs/reference/application-index.md": idx,
    "docs/documentation-maintenance/coverage-matrix.md": cov,
  };
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const out = await renderAll();
  let stale = 0;
  for (const [rel, text] of Object.entries(out)) {
    const path = join(ROOT, rel);
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (check) {
      // A Windows checkout can convert LF to CRLF; that is not a stale page.
      if (current.replace(/\r\n/g, "\n") !== text) {
        console.log(`STALE ${rel} (run: bun run docs:build)`);
        stale++;
      }
    } else {
      writeFileSync(path, text);
      console.log(`wrote ${rel}`);
    }
  }
  if (check) {
    console.log(stale ? `${stale} generated file(s) out of date.` : "Generated documentation is up to date.");
    process.exit(stale ? 1 : 0);
  }
}
void dirname;
