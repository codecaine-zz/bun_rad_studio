#!/usr/bin/env bun
/**
 * App Bundler Studio CLI -- Standalone Binary Compiler & Cross-Platform Desktop App Packager
 * Leverages Bun's native single-file executable compiler (bun build --compile)
 */
import { SimpleCLI } from '../src/index.ts';
import {
  bundleIcon,
  bundleLinuxIcon,
  bundleWindowsIcon,
  ensureAssetsCopied,
  generateLinuxDesktopEntry,
  generatePlist,
  generateWindowsManifest,
} from '../applications/app_bundler_studio.ts';
import * as fs from 'node:fs';
import * as path from 'node:path';

const app = SimpleCLI.newApp('bundler-cli', '1.0.0')
  .setDescription('Native Single-File Executable Compiler & Cross-Platform App Packager (macOS, Windows, Linux)');

app.addFlagString('entry', 'e', './index.ts', 'Entrypoint TypeScript file to compile');
app.addFlagString('name', 'n', 'bun_app', 'Output executable/app name');
app.addFlagString('target', 't', 'bun-darwin-arm64', 'Target: bun-darwin-arm64, bun-darwin-x64, bun-linux-x64, bun-linux-arm64, bun-windows-x64, bun-windows-arm64');
app.addFlagString('out', 'o', './dist', 'Output directory');
app.addFlagBool('minify', 'm', true, 'Minify generated bytecode bundle');
app.addFlagBool('app', 'a', false, 'Package into standalone desktop application bundle (.app, -windows, .AppDir)');
app.addFlagString('id', 'i', 'com.enterprise.app', 'Application Bundle ID');
app.addFlagString('version', 'v', '1.0.0', 'Application bundle version');
app.addFlagString('icon', 'c', '', 'Optional path to application icon (.icns, .png, .ico)');

if (!app.parseCli()) process.exit(0);

const entryPath = path.resolve(process.cwd(), app.getFlagString('entry'));
const appName = app.getFlagString('name');
const targetArch = app.getFlagString('target');
const outDir = path.resolve(process.cwd(), app.getFlagString('out'));
const minify = app.getFlagBool('minify');
const packageApp = app.getFlagBool('app');
const bundleId = app.getFlagString('id');
const version = app.getFlagString('version');
const iconPath = app.getFlagString('icon');

app.banner('App Bundler Studio CLI', 'v1.0.0 - Native Single-File Executable Compiler & App Packager');

if (!fs.existsSync(entryPath)) {
  app.error(`Entry file not found: ${entryPath}`);
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });

async function compileBinary(): Promise<string> {
  const isWin = targetArch.includes('windows');
  const outFileName = isWin && !appName.toLowerCase().endsWith('.exe') ? `${appName}.exe` : appName;
  const binaryOutput = path.join(outDir, outFileName);
  app.info(`Compiling standalone binary for target [${targetArch}]...`);
  app.info(`Source: ${entryPath} -> Output: ${binaryOutput}`);

  const args = ['build', '--compile', `--target=${targetArch}`];
  if (minify) args.push('--minify');
  if (isWin && packageApp) args.push('--windows-hide-console');
  args.push(`--outfile=${binaryOutput}`, entryPath);

  const start = performance.now();
  const proc = Bun.spawn(['bun', ...args], {
    stdout: 'inherit',
    stderr: 'inherit',
  });

  const code = await proc.exited;
  const elapsed = (performance.now() - start).toFixed(2);

  if (code !== 0) {
    throw new Error(`Compiler exited with code ${code}`);
  }

  let sizeMb = 'unknown';
  if (fs.existsSync(binaryOutput)) {
    const st = fs.statSync(binaryOutput);
    sizeMb = (st.size / (1024 * 1024)).toFixed(2) + ' MB';
  }

  app.success(`Compiled binary in ${elapsed}ms | Size: ${sizeMb}`);
  return binaryOutput;
}

function buildMacApp(binPath: string) {
  const bundlePath = path.join(outDir, `${appName}.app`);
  const macosDir = path.join(bundlePath, 'Contents', 'MacOS');
  const resDir = path.join(bundlePath, 'Contents', 'Resources');

  app.info(`Packaging into macOS bundle: ${bundlePath}...`);
  fs.mkdirSync(macosDir, { recursive: true });
  fs.mkdirSync(resDir, { recursive: true });
  ensureAssetsCopied(outDir, bundlePath, 'darwin');

  const targetBin = path.join(macosDir, appName);
  fs.copyFileSync(binPath, targetBin);
  try { fs.chmodSync(targetBin, 0o755); } catch {}

  if (iconPath) {
    const iconRes = bundleIcon(iconPath, bundlePath);
    if (iconRes.success) app.info(iconRes.message);
    else app.warn(iconRes.message);
  }

  const plist = generatePlist(appName, bundleId, version, true);
  fs.writeFileSync(path.join(bundlePath, 'Contents', 'Info.plist'), plist, 'utf8');
  app.success(`Successfully generated macOS bundle: ${bundlePath}`);
}

function buildWindowsApp(binPath: string) {
  const cleanName = appName.replace(/\.exe$/i, '');
  const bundlePath = path.join(outDir, `${cleanName}-windows`);
  app.info(`Packaging into Windows application bundle: ${bundlePath}...`);
  fs.mkdirSync(bundlePath, { recursive: true });
  ensureAssetsCopied(outDir, bundlePath, 'win32');

  const targetExe = path.join(bundlePath, `${cleanName}.exe`);
  fs.copyFileSync(binPath, targetExe);

  const manifestXml = generateWindowsManifest(cleanName, bundleId, version, true);
  fs.writeFileSync(path.join(bundlePath, `${cleanName}.exe.manifest`), manifestXml, 'utf8');

  if (iconPath) {
    const iconRes = bundleWindowsIcon(iconPath, bundlePath, cleanName, targetExe);
    if (iconRes.success) app.info(iconRes.message);
    else app.warn(iconRes.message);
  }

  const launchBatch = `@echo off\r\nsetlocal\r\npushd "%~dp0" || exit /b 1\r\nset "BUN_BE_BUN=1"\r\nif not defined WEBVIEW_PATH if exist "%~dp0lib\\libwebview.dll" set "WEBVIEW_PATH=%~dp0lib\\libwebview.dll"\r\n"%~dp0${cleanName}.exe" %*\r\nset "EXIT_CODE=%errorlevel%"\r\npopd\r\nexit /b %EXIT_CODE%\r\n`;
  fs.writeFileSync(path.join(bundlePath, 'launch.cmd'), launchBatch, 'utf8');

  const shortcutScript = `param([switch]$Uninstall, [switch]$Desktop)\r\n$ErrorActionPreference = 'Stop'\r\n$root = $PSScriptRoot\r\n$folders = @([Environment]::GetFolderPath('Programs'))\r\nif ($Desktop) { $folders += [Environment]::GetFolderPath('Desktop') }\r\n$shell = New-Object -ComObject WScript.Shell\r\nforeach ($folder in $folders) {\r\n  $lnkPath = Join-Path $folder '${cleanName}.lnk'\r\n  if ($Uninstall) {\r\n    if (Test-Path -LiteralPath $lnkPath) { Remove-Item -LiteralPath $lnkPath }\r\n    continue\r\n  }\r\n  New-Item -ItemType Directory -Path $folder -Force | Out-Null\r\n  $link = $shell.CreateShortcut($lnkPath)\r\n  $link.TargetPath = Join-Path $root '${cleanName}.exe'\r\n  $link.WorkingDirectory = $root\r\n  $ico = Join-Path $root '${cleanName}.ico'\r\n  if (Test-Path -LiteralPath $ico) { $link.IconLocation = "$ico,0" }\r\n  $link.Description = '${cleanName} (v${version})'\r\n  $link.Save()\r\n}\r\n`;
  fs.writeFileSync(path.join(bundlePath, 'install-shortcuts.ps1'), shortcutScript, 'utf8');

  app.success(`Successfully generated Windows bundle: ${bundlePath}`);
}

function buildLinuxApp(binPath: string) {
  const bundlePath = path.join(outDir, `${appName}.AppDir`);
  const binDir = path.join(bundlePath, 'usr', 'bin');
  const appsDir = path.join(bundlePath, 'usr', 'share', 'applications');

  app.info(`Packaging into Linux .AppDir bundle: ${bundlePath}...`);
  fs.mkdirSync(binDir, { recursive: true });
  fs.mkdirSync(appsDir, { recursive: true });
  ensureAssetsCopied(outDir, bundlePath, 'linux');

  const targetBin = path.join(binDir, appName);
  fs.copyFileSync(binPath, targetBin);
  try { fs.chmodSync(targetBin, 0o755); } catch {}

  if (iconPath) {
    const iconRes = bundleLinuxIcon(iconPath, bundlePath, appName);
    if (iconRes.success) app.info(iconRes.message);
    else app.warn(iconRes.message);
  }

  const desktopEntry = generateLinuxDesktopEntry(appName, bundleId, version);
  fs.writeFileSync(path.join(bundlePath, `${appName}.desktop`), desktopEntry, 'utf8');
  fs.writeFileSync(path.join(appsDir, `${appName}.desktop`), desktopEntry, 'utf8');

  const appRunScript = `#!/bin/sh\nHERE="$(cd "$(dirname "$0")" && pwd -P)"\nexport BUN_BE_BUN=1\nARCH="$(uname -m 2>/dev/null || echo x86_64)"\nif [ "$ARCH" = "aarch64" ] || [ "$ARCH" = "arm64" ]; then\n  SO="$HERE/usr/lib/libwebview-arm64.so"\nelse\n  SO="$HERE/usr/lib/libwebview-x64.so"\nfi\nif [ -z "$WEBVIEW_PATH" ] && [ -f "$SO" ]; then\n  export WEBVIEW_PATH="$SO"\nfi\nexec "$HERE/usr/bin/${appName}" "$@"\n`;
  const appRunPath = path.join(bundlePath, 'AppRun');
  fs.writeFileSync(appRunPath, appRunScript, { mode: 0o755 });
  try { fs.chmodSync(appRunPath, 0o755); } catch {}

  const installSh = `#!/bin/sh\nset -e\nHERE="$(cd "$(dirname "$0")" && pwd -P)"\nBIN_DIR="\${HOME}/.local/bin"\nAPPS_DIR="\${HOME}/.local/share/applications"\nICON_DIR="\${HOME}/.local/share/icons/hicolor/256x256/apps"\nif [ "\${1:-}" = "--uninstall" ]; then\n  rm -f "$BIN_DIR/${appName}" "$APPS_DIR/${appName}.desktop" "$ICON_DIR/${appName}.png"\n  echo "Uninstalled ${appName}."\n  exit 0\nfi\nmkdir -p "$BIN_DIR" "$APPS_DIR" "$ICON_DIR"\nchmod +x "$HERE/AppRun" "$HERE/usr/bin/${appName}"\nln -sf "$HERE/AppRun" "$BIN_DIR/${appName}"\nif [ -f "$HERE/${appName}.png" ]; then\n  cp "$HERE/${appName}.png" "$ICON_DIR/${appName}.png"\nfi\nsed "s|^Exec=.*|Exec=\\"$HERE/AppRun\\" %F|; s|^Icon=.*|Icon=$HERE/${appName}.png|" "$HERE/${appName}.desktop" > "$APPS_DIR/${appName}.desktop"\necho "Installed ${appName} to $APPS_DIR/${appName}.desktop and $BIN_DIR/${appName}."\n`;
  const installShPath = path.join(bundlePath, 'install.sh');
  fs.writeFileSync(installShPath, installSh, { mode: 0o755 });
  try { fs.chmodSync(installShPath, 0o755); } catch {}

  app.success(`Successfully generated Linux .AppDir bundle: ${bundlePath}`);
}

async function main() {
  try {
    const bin = await compileBinary();
    if (packageApp) {
      if (targetArch.includes('windows')) {
        buildWindowsApp(bin);
      } else if (targetArch.includes('linux')) {
        buildLinuxApp(bin);
      } else {
        buildMacApp(bin);
      }
    }
  } catch (err: any) {
    app.error(`Compilation failed: ${err.message}`);
    process.exit(1);
  }
}

main();
