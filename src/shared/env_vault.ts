/**
 * The logic of the Environment & Secret Vault Studio, kept apart from its window so it can be tested:
 * reading .env text, finding mistakes, hiding secrets, making a shareable example file and comparing two files.
 * Nothing here touches the disk or the clipboard.
 */

export const MASK = "••••••••••••••••";

export interface EnvVar {
  key: string;
  value: string;
  line: number;
  quoted: boolean;
}

export interface ParsedEnv {
  vars: EnvVar[];
  duplicates: string[];
  syntaxErrors: string[];
}

const KEY_RE = /^[A-Za-z_][A-Za-z0-9_.]*$/;

/** Reads `NAME=value` lines. Understands `export NAME=value`, quotes, `# comments` after a value and Windows line endings. */
export function parseEnv(text: string): ParsedEnv {
  const vars: EnvVar[] = [];
  const seen = new Set<string>();
  const duplicates: string[] = [];
  const syntaxErrors: string[] = [];
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    let line = (lines[i] ?? "").trim();
    if (!line || line.startsWith("#")) continue;
    if (/^export\s+/.test(line)) line = line.replace(/^export\s+/, "");
    const eq = line.indexOf("=");
    if (eq === -1) {
      syntaxErrors.push(`Line ${i + 1}: there is no "=" in "${line.slice(0, 60)}"`);
      continue;
    }
    const key = line.slice(0, eq).trim();
    if (!KEY_RE.test(key)) {
      syntaxErrors.push(`Line ${i + 1}: "${key.slice(0, 40)}" is not a valid name (use letters, digits and _, not starting with a digit)`);
      continue;
    }
    const raw = line.slice(eq + 1).trim();
    let value = raw;
    let quoted = false;
    const q = raw[0];
    if (q === '"' || q === "'") {
      const end = raw.indexOf(q, 1);
      if (end === -1) {
        syntaxErrors.push(`Line ${i + 1}: the quote in ${key} is never closed`);
        value = raw.slice(1);
      } else {
        value = raw.slice(1, end);
        quoted = true;
      }
    } else {
      value = raw.replace(/\s+#.*$/, "").trim();
    }
    if (seen.has(key)) {
      if (!duplicates.includes(key)) duplicates.push(key);
    } else seen.add(key);
    vars.push({ key, value, line: i + 1, quoted });
  }
  return { vars, duplicates, syntaxErrors };
}

/** Names that hold secrets. Whole words are matched (so PASSPORT_COUNTRY is not a password, but PASSPORT_SECRET still is). */
export function isSecretKey(key: string): boolean {
  const k = key.toUpperCase();
  if (/SECRET|PASSWORD|PASSWD|TOKEN|CREDENTIAL|PRIVATE|AUTH|SIGNING/.test(k)) return true;
  return k.split(/[_.]/).some((w) => ["KEY", "KEYS", "PASS", "PWD", "SALT", "DSN", "CERT", "PEM"].includes(w));
}

/** Names whose value is a plain setting that is safe to show in an example file. */
function isPlainSetting(key: string): boolean {
  const words = key.toUpperCase().split(/[_.]/);
  return words.includes("PORT") || words.includes("HOST") || (words.includes("NODE") && words.includes("ENV"));
}

export function isSafeExampleValue(key: string, value: string): boolean {
  return !isSecretKey(key) && isPlainSetting(key) && /^[\w.:-]{0,64}$/.test(value);
}

/** Hides the value of every secret. */
export function maskEnv(text: string): string {
  return text
    .split("\n")
    .map((l) => {
      const m = /^(\s*(?:export\s+)?)([A-Za-z_][A-Za-z0-9_.]*)(\s*=)/.exec(l);
      if (!m || !isSecretKey(m[2]!)) return l;
      return `${m[1]}${m[2]}${m[3]}"${MASK}"`;
    })
    .join("\n");
}

/** Puts the real values back after the text was masked. A line the user edited while masked keeps their edit. */
export function unmaskEnv(maskedText: string, rawText: string): string {
  const originals = new Map<string, string[]>();
  for (const l of rawText.split("\n")) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_.]*)\s*=/.exec(l);
    if (m) (originals.get(m[1]!) ?? originals.set(m[1]!, []).get(m[1]!)!).push(l);
  }
  return maskedText
    .split("\n")
    .map((l) => {
      const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_.]*)\s*=\s*["']?(.*?)["']?\s*$/.exec(l);
      if (!m || m[2] !== MASK) return l;
      const queue = originals.get(m[1]!);
      return queue?.length ? queue.shift()! : l;
    })
    .join("\n");
}

/** A shareable template: every name once, secrets and other values blanked (plain ports, hosts and NODE_ENV keep theirs). */
export function makeExample(text: string): { text: string; count: number; kept: number } {
  const { vars } = parseEnv(text);
  const out = ["# Generated .env.example Template", "# Auto-generated by Bun RAD Studio Environment & Secret Vault", ""];
  const done = new Set<string>();
  let kept = 0;
  for (const v of vars) {
    if (done.has(v.key)) continue;
    done.add(v.key);
    if (isSafeExampleValue(v.key, v.value)) {
      out.push(`${v.key}=${v.value}`);
      kept++;
    } else out.push(`${v.key}=""`);
  }
  return { text: out.join("\n") + "\n", count: done.size, kept };
}

export interface EnvDiff {
  activeCount: number;
  templateCount: number;
  missing: string[];
  extra: string[];
  empty: string[];
}

export function diffEnv(active: string, template: string): EnvDiff {
  const a = parseEnv(active);
  const t = parseEnv(template);
  const aKeys = new Set(a.vars.map((v) => v.key));
  const tKeys = new Set(t.vars.map((v) => v.key));
  return {
    activeCount: aKeys.size,
    templateCount: tKeys.size,
    missing: [...tKeys].filter((k) => !aKeys.has(k)),
    extra: [...aKeys].filter((k) => !tKeys.has(k)),
    empty: [...new Set(a.vars.filter((v) => v.value === "" && tKeys.has(v.key)).map((v) => v.key))],
  };
}

export function formatDiff(d: EnvDiff): string {
  const list = (keys: string[], sign: string, none: string) => (keys.length ? keys.map((k) => `  ${sign} ${k}`).join("\n") : `  ${none}`);
  return [
    "ENVIRONMENT COMPARISON",
    `Your settings: ${d.activeCount} names     Example file: ${d.templateCount} names`,
    "",
    `🔴 In the example but not in your settings (${d.missing.length}):`,
    list(d.missing, "-", "(none: every name in the example is set)"),
    "",
    `🟡 In your settings but not in the example (${d.extra.length}):`,
    list(d.extra, "+", "(none)"),
    "",
    `⚪ Set but empty (${d.empty.length}):`,
    list(d.empty, "~", "(none)"),
  ].join("\n");
}

export interface Audit {
  total: number;
  errors: string[];
  warnings: string[];
  duplicates: string[];
}

const PLACEHOLDER = /^(change[_-]?me|your[_-].*|xxx+|todo|example|secret|password|test|<.*>|\.\.\.)$/i;

/** Errors break the file; warnings are things worth a second look. */
export function auditEnv(text: string): Audit {
  const p = parseEnv(text);
  const warnings: string[] = [];
  for (const d of p.duplicates) warnings.push(`${d} appears more than once (the last one usually wins)`);
  for (const v of p.vars) {
    if (v.value === "") warnings.push(`Line ${v.line}: ${v.key} is empty`);
    else if (isSecretKey(v.key) && PLACEHOLDER.test(v.value)) warnings.push(`Line ${v.line}: ${v.key} still looks like a placeholder`);
    if (v.key !== v.key.toUpperCase()) warnings.push(`Line ${v.line}: ${v.key} is not UPPER_CASE (most tools expect that)`);
    if (!v.quoted && /\s/.test(v.value)) warnings.push(`Line ${v.line}: the value of ${v.key} has spaces; put it in quotes`);
  }
  return { total: p.vars.length, errors: p.syntaxErrors, warnings, duplicates: p.duplicates };
}
